-- 014: 2026년 공휴일 시드 (D-74 일부 해소, D-180).
-- [미확인] 출처는 웹의 공휴일 정리 자료(공휴일 계산기·달력 사이트)이며 인사혁신처 고시/공공데이터 특일 정보와 아직 대조하지 않았다.
